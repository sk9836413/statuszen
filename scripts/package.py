"""Build the CodeCanyon download package: dist/Statuszen-<version>.zip

Contents:
  Statuszen-<version>/documentation/   (HTML guide)
  Statuszen-<version>/statuszen/       (the app/ folder: source code, without build output,
                                        dependencies, runtime data or secrets)

public/sz.js is not packaged: `npm run build` / `npm run dev` (prebuild / predev) generate it
from src/status-widget with scripts/build-widget.mjs.

After writing the zip, the script checks it for files that must never ship (env files,
databases, keys, node_modules, build output) and fails if it finds any.

Usage:  python scripts/package.py
"""
import json
import os
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
DOCS = ROOT / "documentation"
VERSION = json.loads((APP / "package.json").read_text(encoding="utf8"))["version"]
NAME = f"Statuszen-{VERSION}"
APP_DIR_IN_ZIP = "statuszen"

EXCLUDE_DIRS = {"node_modules", ".next", ".git", ".vercel", "coverage", ".claude", ".turbo", "out", "build", "dist"}
# vercel.json / .vercelignore belong to our live demo deployment, not the product.
EXCLUDE_FILES = {
    "AGENTS.md",
    "CLAUDE.md",
    "next-env.d.ts",
    ".DS_Store",
    "Thumbs.db",
    "vercel.json",
    ".vercelignore",
}
# Generated by `npm run build` / `npm run dev` from src/status-widget (scripts/build-widget.mjs).
EXCLUDE_PATHS = {"public/sz.js"}
EXCLUDE_SUFFIXES = (
    ".log",
    ".tsbuildinfo",
    ".sqlite",
    ".sqlite3",
    ".db",
    ".pem",
    ".key",
    ".crt",
    ".p12",
    ".pfx",
    "-wal",
    "-shm",
    "-journal",
)


def app_files():
    for path in sorted(APP.rglob("*")):
        rel = path.relative_to(APP)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if path.is_dir():
            continue
        name = rel.name
        if name in EXCLUDE_FILES or name.lower().endswith(EXCLUDE_SUFFIXES):
            continue
        if rel.as_posix() in EXCLUDE_PATHS:
            continue
        if name.startswith(".env") and name != ".env.example":
            continue
        # Runtime data: keep only the placeholder that makes the folder exist.
        if rel.parts[0] == "storage" and name != ".gitkeep":
            continue
        yield path, rel


def problems(names):
    """Names inside the zip that must never be shipped."""
    bad = []
    app_prefix = f"{NAME}/{APP_DIR_IN_ZIP}/"
    for n in names:
        lower = n.lower()
        base = lower.rsplit("/", 1)[-1]
        parts = lower.split("/")
        if any(p in EXCLUDE_DIRS for p in parts):
            bad.append(n)
        elif base.startswith(".env") and base != ".env.example":
            bad.append(n)
        elif base.endswith(EXCLUDE_SUFFIXES) or base in {f.lower() for f in EXCLUDE_FILES}:
            bad.append(n)
        elif n.startswith(app_prefix + "storage/") and base != ".gitkeep":
            bad.append(n)
        elif n == app_prefix + "public/sz.js":
            bad.append(n)
    return bad


def main():
    if not (DOCS / "index.html").is_file():
        print(f"Missing {DOCS / 'index.html'}", file=sys.stderr)
        return 1
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    target = dist / f"{NAME}.zip"
    count = 0
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(DOCS.rglob("*")):
            if path.is_file():
                zf.write(path, f"{NAME}/documentation/{path.relative_to(DOCS).as_posix()}")
                count += 1
        for path, rel in app_files():
            zf.write(path, f"{NAME}/{APP_DIR_IN_ZIP}/{rel.as_posix()}")
            count += 1

    with zipfile.ZipFile(target) as zf:
        names = zf.namelist()
    bad = problems(names)
    if bad:
        target.unlink()
        print("Refusing to ship these files:", *bad, sep="\n  ", file=sys.stderr)
        return 1
    required = [f"{NAME}/documentation/index.html", f"{NAME}/{APP_DIR_IN_ZIP}/package.json", f"{NAME}/{APP_DIR_IN_ZIP}/.env.example", f"{NAME}/{APP_DIR_IN_ZIP}/storage/.gitkeep"]
    missing = [r for r in required if r not in names]
    if missing:
        print("Missing from the package:", *missing, sep="\n  ", file=sys.stderr)
        return 1

    size = os.path.getsize(target) / 1024 / 1024
    print(f"{target} ({count} files, {size:.2f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
