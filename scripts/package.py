"""Build the CodeCanyon download package: dist/Trustzen-<version>.zip

Contents:
  Trustzen-<version>/documentation/   (HTML guide)
  Trustzen-<version>/trustzen/        (the app/ folder: source code, without build output,
                                       dependencies, runtime data or secrets)

public/w.js is not packaged: `npm run build` (prebuild) generates it from src/widget.

Usage:  python scripts/package.py
"""
import json
import os
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
DOCS = ROOT / "documentation"
VERSION = json.loads((APP / "package.json").read_text(encoding="utf8"))["version"]
NAME = f"Trustzen-{VERSION}"
APP_DIR_IN_ZIP = "trustzen"

EXCLUDE_DIRS = {"node_modules", ".next", ".git", ".vercel", "coverage", ".claude", ".turbo", "out", "build"}
# vercel.json / .vercelignore belong to our live demo deployment, not the product.
EXCLUDE_FILES = {
    "AGENTS.md",
    "CLAUDE.md",
    "next-env.d.ts",
    ".DS_Store",
    "Thumbs.db",
    "vercel.json",
    ".vercelignore",
}
# Generated by `npm run build` / `npm run dev` from src/widget (scripts/build-widget.mjs).
EXCLUDE_PATHS = {"public/w.js"}
EXCLUDE_SUFFIXES = (".log", ".tsbuildinfo", ".sqlite", ".sqlite3", ".db", ".pem", ".key")


def app_files():
    for path in sorted(APP.rglob("*")):
        rel = path.relative_to(APP)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if path.is_dir():
            continue
        name = rel.name
        if name in EXCLUDE_FILES or name.lower().endswith(EXCLUDE_SUFFIXES):
            continue
        if rel.as_posix() in EXCLUDE_PATHS:
            continue
        if name.startswith(".env") and name != ".env.example":
            continue
        # Runtime data: keep only the placeholder that makes the folder exist.
        if rel.parts[0] == "storage" and name != ".gitkeep":
            continue
        yield path, rel


def main():
    if not (DOCS / "index.html").is_file():
        print(f"Missing {DOCS / 'index.html'}", file=sys.stderr)
        return 1
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    target = dist / f"{NAME}.zip"
    count = 0
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in sorted(DOCS.rglob("*")):
            if path.is_file():
                zf.write(path, f"{NAME}/documentation/{path.relative_to(DOCS).as_posix()}")
                count += 1
        for path, rel in app_files():
            zf.write(path, f"{NAME}/{APP_DIR_IN_ZIP}/{rel.as_posix()}")
            count += 1
    size = os.path.getsize(target) / 1024 / 1024
    print(f"{target} ({count} files, {size:.2f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
